
from tkinter import *
from datetime import datetime, date
import sqlite3


# СОЗДАНИЕ БАЗЫ ДАННЫХ

# Подключаемся к базе данных events.db.
# Если такой базы ещё нет, SQLite автоматически создаст файл events.db.
# Переменная db хранит соединение с нашей базой данных.
db = sqlite3.connect("events.db")

# Создаём курсор для работы с базой данных.
# db — само подключение к базе, а cursor — инструмент,
# через который мы будем отправлять SQL-запросы (CREATE, INSERT, SELECT).
cursor = db.cursor()

# Создаём таблицу events для хранения наших событий.
# IF NOT EXISTS — создаём таблицу, только если её ещё нет.
# id — уникальный номер события, который выдаётся автоматически.
# event_date — дата события, которую будем хранить как текст.
# name — название события.
# AUTOINCREMENT — при добавлении нового события ID будет выдаваться автоматически.
cursor.execute("CREATE TABLE IF NOT EXISTS events (id INTEGER PRIMARY KEY AUTOINCREMENT, event_date TEXT, name TEXT)")

# Фиксируем изменения в базе данных.
db.commit()


# СПИСКИ ДНЕЙ НЕДЕЛИ И МЕСЯЦЕВ

# Создаём список дней недели.
# Он понадобится, потому что Python определяет дни недели числами от 0 до 6.
# Например, weekday() вернёт 0 для понедельника, 1 для вторника и т.д.
# А мы через этот список сможем выводить название дня на русском языке.
days = ["понедельник", "вторник", "среда", "четверг",
        "пятница", "суббота", "воскресенье"]

# Создаём список месяцев.
# Он нужен, чтобы пользователь выбирал месяц из готового списка,
# а не вводил его название самостоятельно.
months = ["Январь", "Февраль", "Март", "Апрель", "Май", "Июнь",
          "Июль", "Август", "Сентябрь", "Октябрь", "Ноябрь", "Декабрь"]


# СОЗДАНИЕ ГЛАВНОГО ОКНА

# Создаём главное окно нашей программы.
# Tk() — готовый класс из библиотеки tkinter.
# root — переменная, в которой будем хранить главное окно.
root = Tk()

# Задаём название главного окна.
root.title("Календарь событий")

# Задаём размеры окна: 400 пикселей в ширину и 300 в высоту.
root.geometry("400x300")


# ФУНКЦИЯ ДОБАВЛЕНИЯ СОБЫТИЯ

# Создаём функцию add_event.
# Она будет запускаться, когда пользователь нажмёт кнопку "Добавить событие".
# Пока мы только описываем функцию, сама по себе она не выполняется.
def add_event():

    # Создаём дополнительное окно с помощью Toplevel().
    # В отличие от Tk(), Toplevel() создаёт новое окно поверх главного.
    # root в скобках означает, что новое окно связано с главным.
    # win — переменная для работы с этим дополнительным окном.
    win = Toplevel(root)

    # Устанавливаем название и размеры дополнительного окна.
    win.title("Добавить событие")
    win.geometry("350x300")

    # Создаём надпись "Название события:" с помощью Label.
    # win — указываем, что надпись должна находиться во втором окне.
    # text — сам текст надписи.
    # pack() — размещаем надпись в окне.
    # pady=5 — отступы сверху и снизу по 5 пикселей.
    Label(win, text="Название события:").pack(pady=5)

    # Создаём поле для ввода названия события.
    # Entry — поле, в которое пользователь может вводить текст.
    # width=35 — ширина поля в символах, а не в пикселях.
    # name_entry — переменная, в которой хранится наше поле ввода.
    name_entry = Entry(win, width=35)

    # Размещаем созданное поле в окне.
    name_entry.pack()

    # Создаём надпись, которая подсказывает формат ввода даты.
    # дд — день, мм — месяц, гггг — год.
    Label(win, text="Дата события (дд.мм.гггг):").pack(pady=5)

    # Создаём второе поле ввода — уже для даты события.
    date_entry = Entry(win, width=35)
    date_entry.pack()

    # Создаём пустую надпись.
    # Возникает вопрос: зачем создавать надпись, если в ней ничего нет?
    # Потому что позже мы будем выводить в неё сообщения.
    # Например:
    # "Введите название события"
    # "Неверная дата"
    # "Событие добавлено!"
    # То есть сначала создаём пустой Label, а потом меняем его текст.
    info = Label(win, text="")
    info.pack(pady=10)


    # ФУНКЦИЯ СОХРАНЕНИЯ СОБЫТИЯ

    # Создаём функцию save внутри функции add_event.
    # Она будет запускаться при нажатии кнопки "Сохранить".
    # Она находится внутри add_event, потому что нужна только этому окну.
    def save():

        # Получаем текст, который пользователь ввёл в поля.
        # Метод get() позволяет получить содержимое Entry.
        # Например, пользователь написал:
        # name_entry = "Экзамен"
        # date_entry = "25.11.2026"
        # После get() эти значения попадут в переменные name и text_date.
        name = name_entry.get()
        text_date = date_entry.get()

        # Проверяем, ввёл ли пользователь название события.
        # "" — пустая строка.
        # Если название пустое, выводим сообщение в Label info.
        if name == "":
            info["text"] = "Введите название события"

            # return — прекращаем выполнение функции save.
            # Это нужно, чтобы событие без названия не попало в базу.
            return

        # Теперь нужно проверить дату.
        # Пользователь вводит дату как обычный текст, например "25.11.2026".
        # Но для вычисления количества дней нам нужна настоящая дата.
        # Поэтому преобразуем текст в объект даты.

        # try — пробуем выполнить код.
        # Если пользователь ввёл неправильную дату, возникнет ошибка.
        # Например, 45.19.2026 — такой даты не существует.
        try:

            # strptime() преобразует текст в дату по заданному формату.
            # %d — день, %m — месяц, %Y — год из четырёх цифр.
            # .date() оставляет только дату, без времени.
            event_date = datetime.strptime(text_date, "%d.%m.%Y").date()

        # except ValueError — если дата неправильная,
        # не даём программе завершиться с ошибкой.
        # Вместо этого выводим понятное сообщение пользователю.
        except ValueError:
            info["text"] = "Неверная дата"
            return

        # Если название и дата правильные, сохраняем событие в базу.

        # cursor.execute() выполняет SQL-запрос.
        # INSERT INTO — команда добавления новой строки в таблицу.
        # events — название нашей таблицы.
        # event_date и name — столбцы, которые мы заполняем.
        # Вопросительные знаки ? — места для подстановки значений.

        # event_date.isoformat() преобразует дату в формат ГГГГ-ММ-ДД.
        # Например, 25.11.2026 превращается в "2026-11-25".
        # name — название события, которое ввёл пользователь.

        # То есть в базу попадёт примерно такая запись:
        # id = 1
        # event_date = "2026-11-25"
        # name = "Экзамен"
        # ID мы не указываем, потому что SQLite выдаёт его автоматически.
        cursor.execute(
            "INSERT INTO events (event_date, name) VALUES (?, ?)",
            (event_date.isoformat(), name)
        )

        # Фиксируем добавление события в базе данных.
        # Благодаря commit() событие сохранится даже после закрытия программы.
        db.commit()

        # Сообщаем пользователю, что событие успешно добавлено.
        # Мы не создаём новый Label, а меняем текст существующего.
        info["text"] = "Событие добавлено!"

        # Очищаем оба поля ввода после сохранения.
        # delete(0, END) — удалить текст от первого символа до последнего.
        # Это удобно, если пользователь хочет добавить ещё одно событие.
        name_entry.delete(0, END)
        date_entry.delete(0, END)

    # Создаём кнопку "Сохранить".
    # command=save означает, что при нажатии вызовется функция save.
    # Важно: пишем save без (), иначе функция вызовется сразу.
    Button(win, text="Сохранить", command=save).pack(pady=5)

    # Создаём кнопку "Назад".
    # win.destroy закрывает дополнительное окно.
    # Главное окно root при этом продолжает работать.
    Button(win, text="Назад", command=win.destroy).pack()


# ФУНКЦИЯ ПРОСМОТРА СОБЫТИЙ

# Эта функция запускается при нажатии кнопки "Просмотр событий".
# Здесь мы создадим окно с четырьмя фреймами, как требует преподаватель.
def open_events():

    # Создаём ещё одно дополнительное окно.
    win = Toplevel(root)
    win.title("Просмотр событий")
    win.geometry("750x450")

    # Получаем сегодняшнюю дату с помощью date.today().
    # Например, если сегодня 18 ноября 2026 года,
    # в переменной today будет храниться эта дата.
    today = date.today()


    # СОЗДАНИЕ ЧЕТЫРЁХ ФРЕЙМОВ

    # Frame — это контейнер внутри окна.
    # Проще говоря, отдельный блок, в котором можно размещать элементы.
    # По заданию нам нужно четыре фрейма:
    # 1. Верхний — сегодняшняя дата и день недели.
    # 2. Левый — ввод года и выбор месяца.
    # 3. Правый — вывод событий.
    # 4. Нижний — кнопки "Просмотр" и "Назад".

    # Создаём верхний фрейм с голубым фоном.
    top = Frame(win, bg="lightblue")

    # Размещаем его сверху окна.
    # side=TOP — расположить сверху.
    # fill=X — растянуть по всей ширине окна.
    top.pack(side=TOP, fill=X)

    # Создаём надпись с сегодняшней датой и днём недели.
    # strftime("%d.%m.%Y") переводит дату в формат ДД.ММ.ГГГГ.
    # today.weekday() возвращает номер дня недели от 0 до 6.
    # Например, для среды вернётся 2.
    # days[2] — это "среда", поэтому получим название дня на русском.
    # Знак + используется для объединения строк.
    Label(top, text="Сегодня: " + today.strftime("%d.%m.%Y") +
          ", " + days[today.weekday()], bg="lightblue",
          font=("Arial", 14)).pack(pady=10)

    # Создаём нижний фрейм для двух кнопок.
    bottom = Frame(win)

    # side=BOTTOM — размещаем внизу.
    # fill=X — растягиваем по ширине.
    bottom.pack(side=BOTTOM, fill=X, pady=10)

    # Создаём левый фрейм для ввода года и выбора месяца.
    left = Frame(win)

    # side=LEFT — располагаем слева.
    # padx и pady — отступы по горизонтали и вертикали.
    # fill=Y — фрейм растягивается по вертикали.
    left.pack(side=LEFT, padx=15, pady=10, fill=Y)

    # Создаём правый фрейм, в котором будем показывать события.
    right = Frame(win)

    # fill=BOTH — растягиваем по ширине и высоте.
    # expand=True — разрешаем занимать свободное место в окне.
    right.pack(side=LEFT, padx=10, pady=10, fill=BOTH, expand=True)


    # ЛЕВЫЙ ФРЕЙМ — ВВОД ГОДА И ВЫБОР МЕСЯЦА

    # Создаём надпись для ввода года.
    Label(left, text="Введите год:").pack()

    # Создаём поле для года.
    year_entry = Entry(left, width=15)
    year_entry.pack(pady=5)

    # insert() позволяет вставлять текст в поле программным способом.
    # Первый аргумент 0 означает "в начало поля".
    # today.year возвращает текущий год как число.
    # str() превращает число в строку, чтобы вставить его в Entry.
    # Поэтому при открытии окна год уже будет заполнен автоматически.
    year_entry.insert(0, str(today.year))

    # Создаём надпись для выбора месяца.
    Label(left, text="Выберите месяц:").pack(pady=5)

    # Создаём список месяцев с помощью Listbox.
    # height=12 — показывать 12 строк.
    # selectmode=SINGLE — можно выбрать только один месяц.
    # exportselection=0 — выбор не будет сбрасываться,
    # когда пользователь переключается на другое поле.
    month_list = Listbox(left, height=12, selectmode=SINGLE,
                         exportselection=0)
    month_list.pack()

    # Заполняем Listbox названиями месяцев.
    # Цикл for перебирает все элементы списка months.
    # insert(END, month) добавляет очередной месяц в конец Listbox.
    for month in months:
        month_list.insert(END, month)


    # ПРАВЫЙ ФРЕЙМ — ОТОБРАЖЕНИЕ СОБЫТИЙ

    # Создаём заголовок "События" внутри правого фрейма.
    Label(right, text="События", font=("Arial", 14)).pack()

    # Создаём многострочную текстовую область Text.
    # В отличие от Entry, она позволяет выводить несколько строк текста.
    # В ней мы будем показывать названия событий, даты,
    # дни недели и количество прошедших или оставшихся дней.
    result = Text(right, width=45, height=18)
    result.pack(fill=BOTH, expand=True)


    # ФУНКЦИЯ ПОИСКА И ВЫВОДА СОБЫТИЙ

    # Функция запускается при нажатии кнопки "Просмотр".
    # Она получает выбранный год и месяц, ищет события в базе
    # и выводит информацию о них в текстовую область.
    def show_events():

        # Сначала очищаем текстовую область от предыдущих результатов.
        # У Text немного другой формат координат, чем у Entry.
        # 1.0 означает первую строку и первый символ.
        # END — конец всего текста.
        result.delete(1.0, END)

        # Получаем год, который пользователь ввёл в Entry.
        year = year_entry.get()

        # Получаем информацию о выбранном месяце.
        # curselection() возвращает номера выбранных элементов Listbox.
        # Например, если выбран ноябрь, получим (10,).
        # Почему 10? Потому что индексы списков начинаются с нуля.
        selected = month_list.curselection()

        # Проверяем, правильно ли пользователь ввёл год.
        # isdigit() — проверяет, что строка состоит только из цифр.
        # len(year) != 4 — проверяем, что год состоит из 4 цифр.
        # year == "0000" — запрещаем нулевой год.
        # or означает "или": достаточно выполнения одного условия.
        if not year.isdigit() or len(year) != 4 or year == "0000":
            result.insert(END, "Введите правильный год")
            return

        # Проверяем, выбран ли месяц.
        # Если длина selected равна нулю, значит ничего не выбрали.
        if len(selected) == 0:
            result.insert(END, "Выберите месяц")
            return

        # Получаем номер выбранного месяца.
        # selected[0] — индекс выбранного элемента.
        # Прибавляем 1, потому что индексы начинаются с 0,
        # а месяцы нумеруются с 1 до 12.
        # Например, ноябрь: индекс 10, номер месяца 11.
        month = selected[0] + 1

        # Формируем строку для поиска дат в базе данных.
        # str(month) — превращаем номер месяца в строку.
        # zfill(2) — добавляем ноль слева, если число однозначное.
        # Например, месяц 3 превратится в "03".
        # % в конце — специальный символ SQL LIKE,
        # который означает "любое продолжение строки".
        # Например, для ноября 2026 получится "2026-11-%".
        # Такая строка подходит для всех дат ноября 2026 года.
        search_date = year + "-" + str(month).zfill(2) + "-%"

        # Выполняем SQL-запрос к таблице events.
        # SELECT — получить данные из таблицы.
        # event_date, name — получаем дату и название события.
        # WHERE — условие отбора.
        # LIKE — поиск по шаблону.
        # ORDER BY event_date — сортировка по дате.
        # Вопросительный знак заменяется значением search_date.
        cursor.execute(
            "SELECT event_date, name FROM events WHERE event_date LIKE ? ORDER BY event_date",
            (search_date,)
        )

        # fetchall() получает все строки, найденные SQL-запросом.
        # Например, если в ноябре три события,
        # переменная events будет содержать три записи.
        # Если ничего не найдено, получим пустой список.
        events = cursor.fetchall()

        # Проверяем, нашлись ли события.
        # Если длина events равна 0, значит событий нет.
        if len(events) == 0:
            result.insert(END, "Событий нет")
            return

        # Перебираем найденные события по одному.
        # Каждая запись содержит два значения: дату и название.
        # Они автоматически попадут в переменные event_date и name.
        for event_date, name in events:

            # Дата в SQLite хранится как текст в формате ГГГГ-ММ-ДД.
            # С помощью strptime() превращаем её обратно в дату Python.
            # Например, "2026-11-25" станет объектом даты.
            d = datetime.strptime(event_date, "%Y-%m-%d").date()

            # Вычисляем разницу между датой события и сегодняшним днём.
            # d - date.today() — вычитаем из даты события текущую дату.
            # .days — получаем разницу в целых днях.
            #
            # Например:
            # Если событие через 7 дней, difference = 7.
            # Если событие было 5 дней назад, difference = -5.
            # Если событие сегодня, difference = 0.
            difference = (d - date.today()).days

            # Если разница положительная, событие ещё не наступило.
            if difference > 0:
                status = "Осталось дней: " + str(difference)

            # Если разница отрицательная, событие уже прошло.
            # Ставим минус перед difference, чтобы получить
            # положительное количество прошедших дней.
            # Например, -(-5) = 5.
            elif difference < 0:
                status = "Прошло дней: " + str(-difference)

            # Если разница равна нулю, событие происходит сегодня.
            else:
                status = "Сегодня"

            # Выводим всю информацию в текстовую область result.
            # insert(END, ...) — добавляем текст в конец области.
            # \n — переход на новую строку.
            # \n\n — два перехода, чтобы разделить события пустой строкой.

            # Выводим название события.
            result.insert(END, "Событие: " + name + "\n")

            # Выводим дату в привычном формате ДД.ММ.ГГГГ.
            result.insert(END, "Дата: " + d.strftime("%d.%m.%Y") + "\n")

            # Определяем номер дня недели и получаем его название из days.
            result.insert(END, "День недели: " + days[d.weekday()] + "\n")

            # Выводим, сколько дней осталось или прошло.
            result.insert(END, status + "\n\n")


    # НИЖНИЙ ФРЕЙМ — КНОПКИ

    # Создаём кнопку "Просмотр" в нижнем фрейме.
    # command=show_events — при нажатии запускается поиск событий.
    # width=15 — ширина кнопки в символах.
    # side=LEFT — размещаем кнопку слева.
    Button(bottom, text="Просмотр", width=15,
           command=show_events).pack(side=LEFT, padx=20)

    # Создаём кнопку "Назад".
    # command=win.destroy закрывает окно просмотра событий.
    # Главное окно при этом остаётся открытым.
    Button(bottom, text="Назад", width=15,
           command=win.destroy).pack(side=RIGHT, padx=20)


