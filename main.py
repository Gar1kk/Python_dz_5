# Выше мы описали две функции: add_event() и open_events().
# Но сами по себе они ещё не выполнялись.
# Теперь создадим кнопки, которые будут вызывать эти функции.

# Создаём заголовок программы в главном окне.
# root — указываем, что Label находится именно в главном окне.
# font=("Arial", 20) — шрифт Arial размером 20.
Label(root, text="Календарь событий",
      font=("Arial", 20)).pack(pady=15)

# Добавляем логотип программы.
# PhotoImage позволяет загрузить изображение.
# У нас логотип лежит в файле logo.gif рядом с main.py.

# Используем try, потому что картинки может не оказаться в папке
# либо файл может оказаться повреждённым.
try:

    # Загружаем изображение.
    logo = PhotoImage(file="logo.gif")

    # Создаём Label, но вместо текста помещаем в него картинку.
    # Сохраняем logo в переменной, чтобы изображение не исчезло.
    Label(root, image=logo).pack(pady=10)

# Если загрузка изображения не удалась, показываем обычную надпись.
except TclError:
    Label(root, text="Календарь",
          font=("Arial", 24)).pack(pady=10)

# Создаём кнопку "Добавить событие".
# command=add_event связывает кнопку с нашей функцией.
# При нажатии откроется окно добавления события.
Button(root, text="Добавить событие", width=25,
       command=add_event).pack(pady=10)

# Создаём кнопку "Просмотр событий".
# При нажатии запустится функция open_events().
Button(root, text="Просмотр событий", width=25,
       command=open_events).pack(pady=10)


